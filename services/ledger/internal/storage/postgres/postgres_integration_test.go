func TestIntegration_IdempotencySamePayload(t *testing.T) {
	db, teardown := setupTestDB(t)
	defer teardown()

	accountRepo := postgres.NewAccountRepository(db)
	txRepo := postgres.NewTransactionRepository(db)
	ctx := context.Background()

	accA := uuid.New()
	accB := uuid.New()
	accAObj, _ := domain.NewAccount(accA, "client_idem", domain.AccountTypeCustomer, "USD", time.Now().UTC())
	accBObj, _ := domain.NewAccount(accB, "client_idem", domain.AccountTypeMerchant, "USD", time.Now().UTC())
	require.NoError(t, accountRepo.Create(ctx, accAObj))
	require.NoError(t, accountRepo.Create(ctx, accBObj))

	entries := []domain.Entry{
		{AccountID: accA, Amount: 5000, Direction: domain.DirectionDebit, Currency: "USD"},
		{AccountID: accB, Amount: 5000, Direction: domain.DirectionCredit, Currency: "USD"},
	}

	hash := sha256Hex("order_payload")
	txEntity, err := domain.NewTransaction(
		uuid.New(),
		"client_idem",
		"key_idempotent_test",
		hash,
		"Payment for Order 55",
		entries,
		time.Now().UTC(),
	)
	require.NoError(t, err)

	// 1st request: new transaction
	tx1, isNew1, err := txRepo.RecordTransaction(ctx, txEntity, 0)
	require.NoError(t, err)
	assert.True(t, isNew1)

	// 2nd request: retry with identical payload and key
	txRetry, err := domain.NewTransaction(
		uuid.New(), // different random ID generated by client on retry, but same idempotency key and hash
		"client_idem",
		"key_idempotent_test",
		hash,
		"Payment for Order 55",
		entries,
		time.Now().UTC(),
	)
	require.NoError(t, err)

	tx2, isNew2, err := txRepo.RecordTransaction(ctx, txRetry, 0)
	require.NoError(t, err)
	assert.False(t, isNew2, "retry must not be marked as new record")
	assert.Equal(t, tx1.ID, tx2.ID, "must return original transaction ID")
	assert.Equal(t, tx1.IdempotencyKey, tx2.IdempotencyKey)
	assert.Len(t, tx2.Entries, 2)

	// Verify balance was NOT double counted (should be exactly 5000)
	balA, err := accountRepo.GetBalance(ctx, accA)
	require.NoError(t, err)
	assert.Equal(t, int64(5000), balA.Debits)
}

